/** TikTok API for Business; intentionally separate from Login Kit. No environment or persistence. */
export type TikTokBusinessKind = 'TTO' | 'CREATOR';
export interface TikTokBusinessConfig { appId: string; secret: string; redirectUri: string }
export interface TikTokBusinessGrant {
  accessToken: string; refreshToken: string | null; openId: string | null;
  expiresIn: number | null;
}
const object = (x: unknown): Record<string, unknown> => x !== null && typeof x === 'object' && !Array.isArray(x) ? x as Record<string, unknown> : {};
const token = (x: unknown): x is string => typeof x === 'string' && x.length > 0 && x.length <= 16384 && !/[\r\n]/.test(x);
export class TikTokBusinessApi {
  constructor(private readonly config: TikTokBusinessConfig, private readonly request: typeof fetch = fetch) {}
  async exchange(kind: TikTokBusinessKind, authCode: string): Promise<TikTokBusinessGrant> {
    const creator = kind === 'CREATOR';
    const body = creator
      ? { client_id: this.config.appId, client_secret: this.config.secret, grant_type: 'authorization_code', auth_code: authCode, redirect_uri: this.config.redirectUri }
      : { app_id: this.config.appId, secret: this.config.secret, auth_code: authCode };
    // Never follow a redirect carrying the app secret. Never retry a one-use code automatically.
    const response = await this.request(`https://business-api.tiktok.com/open_api/v1.3/${creator ? 'tt_user/oauth2/token' : 'oauth2/access_token'}/`, {
      method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body),
      redirect: 'error', signal: AbortSignal.timeout(15000),
    });
    if (!response.ok) throw new Error('TOKEN_EXCHANGE_FAILED');
    const envelope = object(await response.json());
    const data = object(envelope.data);
    if (envelope.code !== 0 || !token(data.access_token)) throw new Error('TOKEN_EXCHANGE_FAILED');
    if (creator && (!token(data.refresh_token) || !token(data.open_id) || typeof data.expires_in !== 'number' || !Number.isSafeInteger(data.expires_in) || data.expires_in <= 0 || data.expires_in > 31_536_000)) throw new Error('TOKEN_RESPONSE_INVALID');
    return { accessToken: data.access_token, refreshToken: token(data.refresh_token) ? data.refresh_token : null,
      openId: token(data.open_id) ? data.open_id : null, expiresIn: creator ? data.expires_in as number : null };
  }
}
/** Use the authorization URL generated by My Apps, never one invented for a different TikTok product. */
export function businessAuthorizationUrl(template: string, redirectUri: string, state: string): string {
  const url = new URL(template);
  if (url.protocol !== 'https:' || url.username || url.password || url.port || !['business-api.tiktok.com', 'www.tiktok.com', 'business.tiktok.com'].includes(url.hostname)) throw new Error('AUTH_URL_INVALID');
  url.searchParams.set('redirect_uri', redirectUri);
  url.searchParams.set('state', state);
  return url.toString();
}
