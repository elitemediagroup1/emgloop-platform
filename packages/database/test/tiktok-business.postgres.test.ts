import { test } from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { PrismaClient } from '@prisma/client';
import { IamRepository } from '../src/repositories/iam.repository';
import { TikTokBusinessRepository, businessAuthorized, disconnectBusinessInTx } from '../src/repositories/tiktok-business.repository';
const url = process.env.LOOP_TEST_POSTGRES_URL ?? '';
const local = /^postgres(ql)?:\/\/[^@]*@(localhost|127\.0\.0\.1)(:\d+)?\//.test(url);
test('Postgres: atomic replay protection, scope, revocation, permission and offboarding fences', { skip: local ? false : 'Disposable localhost Postgres required' }, async () => {
  const db = new PrismaClient({ datasources: { db: { url } } });
  const org = `tto_${randomUUID()}`, other = `tto_${randomUUID()}`;
  try {
    await db.organization.createMany({ data: [{ id: org, name: 'Test A', slug: org }, { id: other, name: 'Test B', slug: other }] });
    const iam = new IamRepository(db);
    const user = await iam.createUser({ organizationId: org, email: 'tto@example.test', systemRole: 'OWNER' });
    await iam.activateUser(org, user.id);
    const session = await db.userSession.create({ data: { organizationId: org, userId: user.id, expiresAt: new Date(Date.now() + 3600000) } });
    const p = { organizationId: org, userId: user.id, sessionId: session.id };
    const repo = new TikTokBusinessRepository(db);
    assert.equal(await businessAuthorized(db, p, 'CREATOR'), null);
    assert.equal(await repo.begin(p, 'TTO', 'state-a', new Date()), true);
    assert.equal(await repo.consume({ ...p, organizationId: other }, 'TTO', 'state-a', new Date()), false);
    assert.equal(await repo.consume({ ...p, sessionId: 'wrong' }, 'TTO', 'state-a', new Date()), false);
    assert.equal(await repo.consume(p, 'CREATOR', 'state-a', new Date()), false);
    const consumed = await Promise.all(Array.from({ length: 5 }, () => repo.consume(p, 'TTO', 'state-a', new Date())));
    assert.equal(consumed.filter(Boolean).length, 1);
    const grant = { tokenSealed: Buffer.from('opaque-test-ciphertext'), externalId: null, expiresAt: null };
    assert.equal(await repo.store(p, 'TTO', 'state-a', grant, new Date()), true);
    assert.equal(await repo.store(p, 'TTO', 'state-a', grant, new Date()), false);
    await repo.begin(p, 'TTO', 'state-b', new Date());
    await repo.consume(p, 'TTO', 'state-b', new Date());
    await repo.disconnect(p, 'TTO');
    assert.equal(await repo.store(p, 'TTO', 'state-b', grant, new Date()), false);
    assert.equal((await db.tikTokBusinessConnection.findFirst({ where: { organizationId: org } }))?.tokenSealed, null);
    await repo.begin(p, 'TTO', 'state-c', new Date());
    await db.permission.create({ data: { organizationId: org, userId: user.id, resource: 'integrations', action: 'update', effect: 'DENY' } });
    assert.equal(await repo.consume(p, 'TTO', 'state-c', new Date()), false);
    await db.permission.deleteMany({ where: { organizationId: org } });
    await repo.consume(p, 'TTO', 'state-c', new Date());
    await db.$transaction(tx => disconnectBusinessInTx(tx, org, user.id));
    assert.equal(await repo.store(p, 'TTO', 'state-c', grant, new Date()), false);
    const creator = await iam.createUser({ organizationId: org, email: 'creator@example.test', systemRole: 'CREATOR' });
    await iam.activateUser(org, creator.id);
    const creatorSession = await db.userSession.create({ data: { organizationId: org, userId: creator.id, expiresAt: new Date(Date.now() + 3600000) } });
    const cp = { organizationId: org, userId: creator.id, sessionId: creatorSession.id };
    assert.equal(await repo.begin(cp, 'CREATOR', 'creator-no-seat', new Date()), false);
    const profile = await db.creatorProfile.create({ data: { organizationId: org, userId: creator.id, partyId: 'test-party', displayName: 'Test Creator' } });
    assert.equal(await repo.begin(cp, 'TTO', 'creator-agency', new Date()), false);
    assert.equal(await repo.begin(cp, 'CREATOR', 'creator-state', new Date()), true);
    assert.equal(await repo.consume(cp, 'CREATOR', 'creator-state', new Date()), true);
    await db.creatorProfile.delete({ where: { id: profile.id } });
    assert.equal(await repo.store(cp, 'CREATOR', 'creator-state', { ...grant, externalId: 'creator-a' }, new Date()), false);
    await repo.begin(p, 'TTO', 'offboarding', new Date());
    await repo.consume(p, 'TTO', 'offboarding', new Date());
    await repo.store(p, 'TTO', 'offboarding', grant, new Date());
    await iam.disableUser(org, user.id);
    assert.equal((await db.tikTokBusinessConnection.findFirst({ where: { organizationId: org, userId: user.id } }))?.tokenSealed, null);
    await db.userSession.update({ where: { id: session.id }, data: { revokedAt: new Date() } });
    assert.equal(await repo.begin(p, 'TTO', 'state-d', new Date()), false);
  } finally { await db.organization.deleteMany({ where: { id: { in: [org, other] } } }); await db.$disconnect(); }
});
